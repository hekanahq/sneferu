// Embeds packages/templates-default/theme (the files `sneferu init` scaffolds and the compiler uses as the
// default store) into packages/templates-default/src/files.generated.ts. Run `pnpm gen:default-theme` after
// changing the theme folder; a vitest check fails when the two drift apart.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../packages/templates-default', import.meta.url));

export function readThemeFolder(dir: string): { path: string; text: string }[] {
  const walk = (d: string): string[] => readdirSync(d).sort().flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
  return walk(dir).map((p) => ({ path: relative(dir, p).split('\\').join('/'), text: readFileSync(p, 'utf8') }));
}

export function renderGenerated(files: { path: string; text: string }[]): string {
  const lines = files.map((f) => `  ${JSON.stringify(f.path)}: ${JSON.stringify(f.text)},`);
  return `// GENERATED by scripts/gen-default-theme.ts from packages/templates-default/theme. Do not edit: run \`pnpm gen:default-theme\`.\nexport const DEFAULT_THEME_TEXT: Readonly<Record<string, string>> = {\n${lines.join('\n')}\n};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, 'src/files.generated.ts'), renderGenerated(readThemeFolder(join(root, 'theme'))));
  console.log('wrote packages/templates-default/src/files.generated.ts');
}
