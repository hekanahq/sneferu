// Renders docs/reference/tags.md from the tag registry. Pure: no file access,
// so the vitest check and the generator produce byte-identical output.
import type { Field, HkTag, TagRegistry } from '@hekana/sneferu-core';

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const cell = (s: string) => s.replace(/\|/g, '\\|');
const code = (v: unknown) => `\`${cell(typeof v === 'string' ? v : JSON.stringify(v))}\``;

function constraints(f: Field): string {
  const out: string[] = [];
  if (f.options?.length) out.push(f.options.map(code).join(' '));
  if (f.min !== undefined) out.push(`min ${f.min}`);
  if (f.max !== undefined) out.push(`max ${f.max}`);
  if (f.step !== undefined) out.push(`step ${f.step}`);
  if (f.maxLength !== undefined) out.push(`max length ${f.maxLength}`);
  if (f.required) out.push('required');
  return out.join(', ') || '';
}

function children(t: HkTag): string {
  if (t.allowedChildren === '*') return 'any content (elements, `hk-*` tags, text)';
  if (t.allowedChildren.length === 0) return 'none (self-closing: `<' + t.name + ' … />`)';
  return t.allowedChildren.map((c) => (c === '#text' ? 'text and `{{ }}`' : `\`<${c}>\``)).join(', ');
}

function tagSection(t: HkTag): string {
  const lines = [
    `## \`<${t.name}>\``,
    '',
    `${t.editor.label.en} · ${t.editor.label.ar}`,
    '',
    `| | |`,
    `|---|---|`,
    `| Category | ${t.category} |`,
    `| Children | ${children(t)} |`,
    `| Responsive props | ${t.responsive.length ? t.responsive.map((p) => code(kebab(p))).join(' ') : 'none'} |`,
    '',
  ];
  const props = Object.entries(t.props);
  if (props.length) {
    lines.push('| Attribute | Type | Default | Responsive | Options / range | Label (en · ar) |', '|---|---|---|---|---|---|');
    for (const [name, f] of props) {
      const responsive = t.responsive.includes(name);
      lines.push(`| ${code(kebab(name))} | ${f.type} | ${f.default === undefined ? '—' : code(f.default)} | ${responsive ? `yes: ${code(`tablet-${kebab(name)}`)} ${code(`mobile-${kebab(name)}`)}` : 'no'} | ${constraints(f) || '—'} | ${cell(f.label.en)} · ${cell(f.label.ar)} |`);
    }
  } else lines.push('No props.');
  lines.push('');
  return lines.join('\n');
}

export function renderTagDocs(registry: TagRegistry): string {
  const tags = [...registry.names()].map((n) => registry.get(n)!);
  const order = ['layout', 'typography', 'media', 'ui', 'commerce', 'checkout', 'control'];
  const byCat = order.map((c) => [c, tags.filter((t) => t.category === c)] as const).filter(([, ts]) => ts.length);
  const out = [
    '# Tag reference',
    '',
    '<!-- GENERATED by scripts/gen-tag-docs.ts from createDefaultRegistry(). Do not edit by hand: run `pnpm docs:tags`. -->',
    '',
    `${tags.length} built-in \`hk-*\` tags. Write props as kebab-case attributes (\`padding-y\` sets the prop \`paddingY\`).`,
    'A responsive prop also takes `tablet-<attr>` (≤ 1023px) and `mobile-<attr>` (≤ 639px); a prefix on any other prop is SN2004.',
    'Unknown props are SN2004, missing required props SN2005, children a tag does not accept SN2006.',
    '',
    'Every tag also accepts the passthrough attributes `class`, `id`, `role`, `title`, `data-*` and `aria-*`, written on its root element',
    '(`class` and `id` reduced to safe tokens; `data-hk-*` is reserved and dropped). They are not listed per tag.',
    '',
    'Colour props take `#hex` or `theme:<token>` (e.g. `theme:accent` → `var(--hk-color-accent)`); anything else is ignored.',
    'Number props are clamped to their range when rendered.',
    '',
    '| Category | Tags |',
    '|---|---|',
    ...byCat.map(([c, ts]) => `| ${c} | ${ts.map((t) => `[\`${t.name}\`](#${t.name})`).join(' ')} |`),
    '',
    'Built into the language (not in the registry): `<hk-schema>` (settings JSON), `<hk-slot name="content" />` and `<hk-sections />` (layout and templates only),',
    '`<hk-block of="{{ block }}" />` (renders a block inside a section). See [language.md](../language.md).',
    '',
  ];
  for (const [, ts] of byCat) for (const t of ts) out.push(tagSection(t));
  return `${out.join('\n').trimEnd()}\n`;
}
