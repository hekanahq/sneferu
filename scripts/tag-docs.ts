// Renders the tag reference from the tag registry: docs/reference/tags.mdx (the
// page, one <TagProps tag="…" /> per tag) and docs/reference/tags.json (the
// registry data <TagProps> renders, so the props on hekana.dev cannot drift from
// the registry). renderTagDocs keeps the plain-markdown form for anything that
// cannot render MDX. Pure: no file access, so the vitest check and the generator
// produce byte-identical output.
import type { Field, HkTag, TagRegistry } from '@hekana/sneferu-core';

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const cell = (s: string) => s.replace(/\|/g, '\\|');
const code = (v: unknown) => `\`${cell(typeof v === 'string' ? v : JSON.stringify(v))}\``;

function constraints(f: Field): string {
  const out: string[] = [];
  if (f.options?.length) out.push(f.options.map(code).join(' '));
  if (f.min !== undefined) out.push(`min ${f.min}`);
  if (f.max !== undefined) out.push(`max ${f.max}`);
  if (f.step !== undefined) out.push(`step ${f.step}`);
  if (f.maxLength !== undefined) out.push(`max length ${f.maxLength}`);
  if (f.required) out.push('required');
  return out.join(', ') || '';
}

function children(t: HkTag): string {
  if (t.allowedChildren === '*') return 'any content (elements, `hk-*` tags, text)';
  if (t.allowedChildren.length === 0) return 'none (self-closing: `<' + t.name + ' … />`)';
  return t.allowedChildren.map((c) => (c === '#text' ? 'text and `{{ }}`' : `\`<${c}>\``)).join(', ');
}

function tagSection(t: HkTag): string {
  const lines = [
    `## \`<${t.name}>\``,
    '',
    t.editor.label.en,
    '',
    `| | |`,
    `|---|---|`,
    `| Category | ${t.category} |`,
    `| Children | ${children(t)} |`,
    `| Responsive props | ${t.responsive.length ? t.responsive.map((p) => code(kebab(p))).join(' ') : 'none'} |`,
    ...(t.parts?.length ? [`| Parts | ${t.parts.map((p) => code(p)).join(' ')} (\`<hk-part name="…">\`) |`] : []),
    '',
  ];
  const props = Object.entries(t.props);
  if (props.length) {
    lines.push('| Attribute | Type | Default | Responsive | Options / range | Label |', '|---|---|---|---|---|---|');
    for (const [name, f] of props) {
      const responsive = t.responsive.includes(name);
      lines.push(`| ${code(kebab(name))} | ${f.type} | ${f.default === undefined ? '—' : code(f.default)} | ${responsive ? `yes: ${code(`tablet-${kebab(name)}`)} ${code(`mobile-${kebab(name)}`)}` : 'no'} | ${constraints(f) || '—'} | ${cell(f.label.en)} |`);
    }
  } else lines.push('No props.');
  lines.push('');
  return lines.join('\n');
}

export function renderTagDocs(registry: TagRegistry): string {
  const tags = [...registry.names()].map((n) => registry.get(n)!);
  const order = ['layout', 'typography', 'media', 'ui', 'commerce', 'control'];
  const byCat = order.map((c) => [c, tags.filter((t) => t.category === c)] as const).filter(([, ts]) => ts.length);
  const out = [
    '# Tag reference',
    '',
    '<!-- GENERATED by scripts/gen-tag-docs.ts from createDefaultRegistry(). Do not edit by hand: run `pnpm docs:tags`. -->',
    '',
    `${tags.length} built-in \`hk-*\` tags. Write props as kebab-case attributes (\`padding-y\` sets the prop \`paddingY\`).`,
    'A responsive prop also takes `tablet-<attr>` (≤ 1023px) and `mobile-<attr>` (≤ 639px); a prefix on any other prop is SN2004.',
    'Unknown props are SN2004, missing required props SN2005, children a tag does not accept SN2006.',
    '',
    'Every tag also accepts the passthrough attributes `class`, `id`, `role`, `title`, `data-*` and `aria-*`, written on its root element',
    '(`class` and `id` reduced to safe tokens; `data-hk-*` is reserved and dropped). They are not listed per tag.',
    '',
    'Colour props take `#hex` or `theme:<token>` (e.g. `theme:accent` → `var(--hk-color-accent)`); anything else is ignored.',
    'Number props are clamped to their range when rendered.',
    '',
    '| Category | Tags |',
    '|---|---|',
    ...byCat.map(([c, ts]) => `| ${c} | ${ts.map((t) => `[\`${t.name}\`](#${t.name})`).join(' ')} |`),
    '',
    'Built into the language (not in the registry): `<hk-schema>` (settings JSON), `<hk-slot name="content" />` and `<hk-sections />` (layout and templates only),',
    '`<hk-block of="{{ block }}" />` (renders a block inside a section), `<hk-part name="…">` (fills a named part of a tag that has parts, such as `hk-product-card`). See [language.md](../language.md).',
    '',
  ];
  for (const [, ts] of byCat) for (const t of ts) out.push(tagSection(t));
  return `${out.join('\n').trimEnd()}\n`;
}

/** The registry as data, for <TagProps> on hekana.dev (docs/reference/tags.json). */
export interface TagDocProp {
  name: string;
  attr: string;
  type: string;
  default?: unknown;
  required?: boolean;
  min?: number;
  max?: number;
  step?: number;
  maxLength?: number;
  options?: string[];
  responsive: boolean;
  label: { en: string };
}
export interface TagDoc {
  name: string;
  category: HkTag['category'];
  label: { en: string };
  allowedChildren: string[] | '*';
  parts?: string[];
  responsive: string[];
  props: TagDocProp[];
}

const ORDER = ['layout', 'typography', 'media', 'ui', 'commerce', 'control'];

function orderedTags(registry: TagRegistry): HkTag[] {
  const tags = [...registry.names()].map((n) => registry.get(n)!);
  return ORDER.flatMap((c) => tags.filter((t) => t.category === c));
}

export function tagRegistryData(registry: TagRegistry): string {
  const tags: TagDoc[] = orderedTags(registry).map((t) => ({
    name: t.name,
    category: t.category,
    label: { en: t.editor.label.en },
    allowedChildren: t.allowedChildren,
    ...(t.parts?.length ? { parts: t.parts } : {}),
    responsive: t.responsive.map(kebab),
    props: Object.entries(t.props).map(([name, f]) => ({
      name,
      attr: kebab(name),
      type: f.type,
      ...(f.default === undefined ? {} : { default: f.default }),
      ...(f.required ? { required: true } : {}),
      ...(f.min === undefined ? {} : { min: f.min }),
      ...(f.max === undefined ? {} : { max: f.max }),
      ...(f.step === undefined ? {} : { step: f.step }),
      ...(f.maxLength === undefined ? {} : { maxLength: f.maxLength }),
      ...(f.options?.length ? { options: f.options } : {}),
      responsive: t.responsive.includes(name),
      label: { en: f.label.en },
    })),
  }));
  return `${JSON.stringify({ generatedBy: 'scripts/gen-tag-docs.ts', tags }, null, 2)}\n`;
}

/** docs/reference/tags.mdx: the same page as tags.md, each tag's tables as <TagProps>. */
export function renderTagDocsMdx(registry: TagRegistry): string {
  const tags = orderedTags(registry);
  const byCat = ORDER.map((c) => [c, tags.filter((t) => t.category === c)] as const).filter(([, ts]) => ts.length);
  const out = [
    '# Tag reference',
    '',
    '{/* GENERATED by scripts/gen-tag-docs.ts from createDefaultRegistry(), with tags.json. Do not edit by hand: run `pnpm docs:tags`. */}',
    '',
    `${tags.length} built-in \`hk-*\` tags. Write props as kebab-case attributes (\`padding-y\` sets the prop \`paddingY\`).`,
    'A responsive prop also takes `tablet-<attr>` (≤ 1023px) and `mobile-<attr>` (≤ 639px); a prefix on any other prop is SN2004.',
    'Unknown props are SN2004, missing required props SN2005, children a tag does not accept SN2006.',
    '',
    'Every tag also accepts the passthrough attributes `class`, `id`, `role`, `title`, `data-*` and `aria-*`, written on its root element',
    '(`class` and `id` reduced to safe tokens; `data-hk-*` is reserved and dropped). They are not listed per tag.',
    '',
    'Colour props take `#hex` or `theme:<token>` (e.g. `theme:accent` → `var(--hk-color-accent)`); anything else is ignored.',
    'Number props are clamped to their range when rendered.',
    '',
    '| Category | Tags |',
    '| - | - |',
    ...byCat.map(([c, ts]) => `| ${c} | ${ts.map((t) => `[\`${t.name}\`](#${t.name})`).join(' ')} |`),
    '',
    'Built into the language (not in the registry): `<hk-schema>` (settings JSON), `<hk-slot name="content" />` and `<hk-sections />` (layout and templates only),',
    '`<hk-block of="{{ block }}" />` (renders a block inside a section), `<hk-part name="…">` (fills a named part of a tag that has parts, such as `hk-product-card`). See [language.mdx](../language.mdx).',
    '',
  ];
  for (const t of tags) {
    out.push(`## \`<${t.name}>\``, '', `<TagProps tag="${t.name}" />`, '');
    if (t.parts?.length) out.push(`Parts, each filled with \`<hk-part name="…">\` directly inside the tag: ${t.parts.map((p) => `\`${p}\``).join(', ')}.`, '');
  }
  return `${out.join('\n').trimEnd()}\n`;
}
